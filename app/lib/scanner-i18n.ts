export const DICTIONARY: Record<Lang, Record<TextKey, string>> = { id, nl };

export type Vars = Record<string, string | number>;

/** Translate a key. Placeholders `{name}` are replaced from `vars`. */
export function t(lang: Lang, key: TextKey, vars?: Vars): string {
  const text = DICTIONARY[lang][key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : text;
}

export function isLang(value: unknown): value is Lang {
  return value === "id" || value === "nl";
}

/** Language from the cookie, else from Accept-Language (nl* = Dutch), else Indonesian. Pure, safe on the server. */
export function detectLang(cookieHeader: string | null, acceptLanguage: string | null): Lang {
  const m = cookieHeader?.match(new RegExp(`(?:^|;\\s*)${LANG_COOKIE}=(\\w+)`));
  if (m && isLang(m[1])) return m[1];
  const first = acceptLanguage?.split(",")[0]?.trim().toLowerCase() ?? "";
  return first.startsWith("nl") ? "nl" : "id";
}

